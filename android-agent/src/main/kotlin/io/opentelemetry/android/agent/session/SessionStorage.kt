package io.opentelemetry.android.agent.session

import io.opentelemetry.android.Incubating
import io.opentelemetry.android.session.Session

/**
 * Storage for sessions written by the agent's built-in session manager.
 *
 * The manager does not read or write storage during construction. It saves each newly generated
 * session, starting on the first session access. This replaces any previously stored session.
 * It reads [getPreviousSession] before the first save, only to link the first session-start event.
 * It does not call [get] to restore a session, so supplying persistent storage alone does not
 * enable session restoration.
 *
 * Calls run synchronously on the calling thread, including during SDK initialization and
 * telemetry recording. Implementations must be thread-safe, return promptly, and handle their
 * own failures without throwing. Saves and observer notifications run in order without holding
 * the manager's lock. Concurrent reads return the current session while those calls run; another
 * session change is deferred until they finish and a subsequent access detects expiry.
 * The manager does not provide a storage fallback or manage storage cleanup.
 */
@Incubating
interface SessionStorage {
    /** Returns the session held by this storage. The built-in manager does not currently read it. */
    fun get(): Session

    /**
     * Returns the previous process's session for startup attribution, or null for no link.
     * Called once on first session access, before [save], outside the manager's lock.
     * Implementations own loading and restart policy and may return an already cached value.
     * The returned session is not restored and receives no session-end notification.
     * An empty ID is treated as no link. Later rotations link to the current process's session.
     */
    fun getPreviousSession(): Session? = null

    /** Saves [newSession] after it is generated by the manager. */
    fun save(newSession: Session)
}
